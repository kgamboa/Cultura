// Compilación del cliente SOLO para el despliegue en Railway (Dockerfile).
//
// El build normal del artefacto (client/build.mjs → @hatch/space-sdk/build)
// solo corre dentro del pipeline de Muse y se niega a ejecutarse en otro
// entorno, así que el contenedor de Railway usa este script equivalente:
// mismo entrypoint (client/index.html), misma salida (client/dist), modo
// producción y el plugin de Tailwind, directamente con Bun.build.
//
// No lo usa el artefacto dentro de Muse; ahí manda client/build.mjs.
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import tailwindPlugin from "bun-plugin-tailwind";

const ENTRY = "./client/index.html";
const OUTDIR = "./client/dist";

// La macro `actionFields` del cliente carga server/src/actions.ts, que
// importa los contratos desde "@space/privileged"; ese alias apunta a
// server/.generated/privileged.contract.ts, un archivo que el pipeline de
// Muse genera desde server/src/privileged.ts. Aquí se genera igual:
// copia verbatim de la llamada definePrivilegedContracts(...) original.
async function generatePrivilegedContract() {
  const src = await readFile("./server/src/privileged.ts", "utf8");
  const marker = "export const Pg = definePrivilegedContracts(";
  const start = src.indexOf(marker);
  if (start < 0) throw new Error("No se encontró definePrivilegedContracts en server/src/privileged.ts");
  let i = start + marker.length;
  let depth = 1;
  let state = "code"; // code | line-comment | block-comment | single | double | template
  while (i < src.length && depth > 0) {
    const c = src[i];
    const next = src[i + 1] ?? "";
    if (state === "code") {
      if (c === "/" && next === "/") state = "line-comment";
      else if (c === "/" && next === "*") state = "block-comment";
      else if (c === "'") state = "single";
      else if (c === '"') state = "double";
      else if (c === "`") state = "template";
      else if (c === "(") depth++;
      else if (c === ")") depth--;
    } else if (state === "line-comment") {
      if (c === "\n") state = "code";
    } else if (state === "block-comment") {
      if (c === "*" && next === "/") { state = "code"; i++; }
    } else {
      if (c === "\\") i++;
      else if ((state === "single" && c === "'") || (state === "double" && c === '"') || (state === "template" && c === "`")) state = "code";
    }
    i++;
  }
  if (depth !== 0) throw new Error("No se pudo extraer el contrato privilegiado (paréntesis sin cerrar)");
  const call = src.slice(start, i);
  await mkdir("./server/.generated", { recursive: true });
  await writeFile(
    "./server/.generated/privileged.contract.ts",
    "// Generated by client/build-railway.mjs from server/src/privileged.ts. Do not edit.\n" +
      'import { definePrivilegedContracts, z } from "@hatch/space-sdk";\n\n' +
      call + ";\n",
  );
}

await generatePrivilegedContract();

await rm(OUTDIR, { force: true, recursive: true });

const platformVersion = await readFile("./space.json", "utf8")
  .then((text) => JSON.parse(text).platformVersion)
  .catch(() => undefined);

const result = await Bun.build({
  entrypoints: [ENTRY],
  outdir: OUTDIR,
  minify: true,
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
    __HATCH_SPACE_PLATFORM_VERSION__: JSON.stringify(
      typeof platformVersion === "number" ? platformVersion : 0,
    ),
  },
  naming: {
    asset: "assets/[name]-[hash].[ext]",
    chunk: "assets/[name]-[hash].[ext]",
    entry: "[name].[ext]",
  },
  plugins: [tailwindPlugin],
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

// Igual que el build canónico: Bun escribe los assets importados en
// `assets/<name>-<hash>.<ext>` pero emite su URL como `./<name>-<hash>.<ext>`;
// se re-prefija a `./assets/...` para que el servidor estático los encuentre.
const assetFiles = result.outputs
  .filter((output) => output.kind === "asset")
  .map((output) => basename(output.path));
for (const output of result.outputs) {
  if (!/\.(js|css|html)$/.test(output.path)) continue;
  let text = await output.text();
  let changed = false;
  for (const name of assetFiles) {
    const bare = `./${name}`;
    if (text.includes(bare)) {
      text = text.split(bare).join(`./assets/${name}`);
      changed = true;
    }
  }
  if (changed) await Bun.write(output.path, text);
}

console.log(`Cliente compilado en ${OUTDIR} (${result.outputs.length} archivos).`);
